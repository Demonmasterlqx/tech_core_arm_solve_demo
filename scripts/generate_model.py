#!/usr/bin/env python3
"""Assemble unchanged, metre-scale HKUST mesh assets into the MuJoCo fixture.

Visual geometry is imported, never replaced by collision primitives. The energy
unit uses the official CAD exterior and the explicitly documented rulebook bore.
Runtime remains C++ only; this generator uses Python's standard library.
"""
from math import cos, sin, pi, sqrt
from pathlib import Path
import json
from xml.etree.ElementTree import Element, SubElement, Comment, indent, tostring

ROOT=Path(__file__).resolve().parents[1]
CORE=json.loads((ROOT/'models/meshes/core/manifest.json').read_text())
ENERGY=json.loads((ROOT/'models/meshes/energy_unit_rule/manifest.json').read_text())
N=48
PIVOT=(-.169,0,.208)

def fmt(v):return ' '.join(f'{x:.12g}' for x in v)
def add(parent,tag,**kw):return SubElement(parent,tag,{k:fmt(v) if isinstance(v,(tuple,list)) else str(v) for k,v in kw.items()})
def geom(parent,name,kind,**kw):return add(parent,'geom',name=name,type=kind,**kw)

def wedge(asset,name,inner,outer,length):
    a=pi/N;vs=[]
    for x in (0,length):
        for r,t in ((inner/cos(a),-a),(outer,-a),(outer,a),(inner/cos(a),a)):
            vs.extend((x,r*cos(t),r*sin(t)))
    faces=(0,2,1,0,3,2,4,5,6,4,6,7,0,1,5,0,5,4,1,2,6,1,6,5,2,3,7,2,7,6,3,0,4,3,4,7)
    add(asset,'mesh',name=name,vertex=vs,face=faces)

m=Element('mujoco',model='RM2026 technology core / original HKUST meshes')
m.append(Comment(' Generated by scripts/generate_model.py. All visible core vertices retain original evaluated Blender geometry at scale 1. See reference/hkust/source.json and mesh manifests. '))
add(m,'compiler',angle='radian',autolimits='true',inertiafromgeom='auto')
opt=add(m,'option',timestep=.001,integrator='implicitfast',gravity=(0,0,-9.81),iterations=80,tolerance='1e-9',cone='elliptic')
add(opt,'flag',filterparent='disable')
add(m,'size',njmax=2000,nconmax=1000)
add(m,'statistic',center=(-.16,0,.78),extent=1.8)
v=add(m,'visual');add(v,'global',offwidth=1440,offheight=1000)
add(v,'quality',shadowsize=2048,offsamples=4)
add(v,'headlight',ambient=(.4,.4,.42),diffuse=(.65,.65,.65),specular=(.25,.25,.25))
add(v,'rgba',haze=(.11,.13,.16,1))
d=add(m,'default')
add(d,'geom',contype=0,conaffinity=0,condim=4,friction=(.35,.005,.0001),solref=(.004,1),solimp=(.95,.99,.001),margin=0,mass=0)
add(d,'joint',limited='true',armature=.0001)
add(d,'site',size=.002,rgba=(0,0,0,0))
a=add(m,'asset')
add(a,'texture',name='floor_texture',type='2d',builtin='checker',width=256,height=256,rgb1=(.16,.18,.21),rgb2=(.18,.20,.23))
add(a,'texture',name='sky',type='skybox',builtin='gradient',rgb1=(.1,.12,.15),rgb2=(.32,.35,.4),width=256,height=1536)
add(a,'material',name='floor',texture='floor_texture',texrepeat=(6,6),reflectance=.08)
for part in CORE['meshes']:
    add(a,'mesh',name='hkust_'+part['name'],file='meshes/core/'+part['file'],inertia='shell')
for part in ENERGY['meshes']:
    if part.get('default_visible',True):
        add(a,'mesh',name=part['name'],file='meshes/energy_unit_rule/'+part['file'],inertia='shell')
        add(a,'material',name=part['name']+'_material',rgba=part['rgb_srgb']+[1],specular=.4,shininess=.35)
wedge(a,'collision_unit_flange',.020,.040,.025)
wedge(a,'collision_unit_tube',.020,.0325,.075)
world=add(m,'worldbody')
geom(world,'ground','plane',size=(3,3,.1),material='floor',contype=16,conaffinity=15)
add(world,'light',name='key',pos=(2,-1.5,3),dir=(-.5,.3,-.7),diffuse=(.7,.72,.76))
add(world,'light',name='fill',pos=(1,2,1.7),dir=(-.6,-.5,-.4),diffuse=(.45,.48,.53),castshadow='false')
add(world,'camera',name='overview',pos=(1.7,-1.4,1.2),xyaxes=(.636,.772,0,-.126,.104,.987),fovy=39)
for i in range(2):
    pref=f'core{i}'
    base=add(world,'body',name=f'{pref}_base',mocap='true',pos=(-.09,.2-.4*i,.6))
    add(base,'site',name=f'{pref}_origin',pos=(0,0,0))
    # Fixed P reference: its 208mm elevation does not move with the lift. The
    # slider moves inside the rotated P/Q frame, reaching a108mm arm at full lift.
    q=add(base,'body',name=f'{pref}_q_bearing',pos=PIVOT)
    add(q,'inertial',pos=(0,0,0),mass=.3,diaginertia=(.001,.001,.001))
    add(q,'joint',name=f'{pref}_twist',type='hinge',axis=(1,0,0),range=(-pi/2,pi/2),damping=0,frictionloss=0)
    p=add(q,'body',name=f'{pref}_p_bearing')
    add(p,'inertial',pos=(.09,0,-.06),mass=.45,diaginertia=(.0006,.0025,.0025))
    add(p,'joint',name=f'{pref}_flip',type='hinge',axis=(0,-1,0),range=(0,pi/2),damping=.15,frictionloss=.02)
    lift=add(p,'body',name=f'{pref}_carriage',pos=(-PIVOT[0],0,-PIVOT[2]))
    add(lift,'inertial',pos=(-.15,0,.025),mass=.6,diaginertia=(.002,.002,.001))
    add(lift,'joint',name=f'{pref}_lift',type='slide',axis=(0,0,1),range=(0,.1),damping=0,frictionloss=10)
    add(lift,'site',name=f'{pref}_tip',pos=(0,0,0))
    add(lift,'site',name=f'{pref}_marker',pos=(-.1,0,0))
    # Each mesh is still in the same E-relative source frame; the only movement
    # is the measured joint transform of its rigid body.
    for part in CORE['meshes']:
        name=part['name'];obj=part['object']
        parent=base if part['motion_group']=='station' else lift
        light=obj.startswith(('back_light_bar_','back_main_light_','pillar_L_light_','pillar_side_light_'))
        mat=f'{pref}_{name}_mat'
        rgb=part['rgba_srgb']
        if light:rgb=(.9,.02,.035,1) if i==0 else(.02,.12,.95,1)
        add(a,'material',name=mat,rgba=rgb,specular=.25 if light else .4,shininess=.3,emission=.6 if light else 0)
        geom(parent,f'{pref}_{name}','mesh',mesh='hkust_'+name,material=mat,group=0)
    # Invisible contact shells: visual topology above is not convexified.
    pole_bit,unit_bit=(1,2) if i==0 else(4,8)
    geom(lift,f'{pref}_peg','cylinder',pos=(-.05,0,0),size=(.018,.05),quat=(sqrt(.5),0,sqrt(.5),0),
         contype=pole_bit,conaffinity=unit_bit,rgba=(0,0,0,0),group=3)
    unit=add(lift,'body',name=f'{pref}_energy_unit')
    add(unit,'inertial',pos=(.075,0,0),mass=.4,diaginertia=(.00026,.00085,.00085))
    add(unit,'joint',name=f'{pref}_insert',type='slide',axis=(-1,0,0),range=(0,.1),damping=0,frictionloss=10)
    add(unit,'site',name=f'{pref}_grip',pos=(.0725,0,0))
    add(unit,'site',name=f'{pref}_opening',pos=(0,0,0))
    for part in ENERGY['meshes']:
        if part.get('default_visible',True):
            geom(unit,f'{pref}_unit_visual_{part["name"]}','mesh',mesh=part['name'],material=part['name']+'_material',group=2)
    for j in range(N):
        for part,x,mesh in [('flange',0,'collision_unit_flange'),('tube',.025,'collision_unit_tube')]:
            geom(unit,f'{pref}_unit_{part}_{j}','mesh',mesh=mesh,pos=(x,0,0),euler=(2*pi*j/N,0,0),
                 contype=unit_bit,conaffinity=pole_bit,rgba=(0,0,0,0),group=3)
    geom(unit,f'{pref}_unit_iron','cylinder',pos=(.105,0,0),size=(.0325,.005),quat=(sqrt(.5),0,sqrt(.5),0),
         contype=unit_bit,conaffinity=pole_bit,rgba=(0,0,0,0),group=3)
    geom(unit,f'{pref}_unit_cap','cylinder',pos=(.13,0,0),size=(.0475,.02),quat=(sqrt(.5),0,sqrt(.5),0),
         contype=unit_bit,conaffinity=pole_bit,rgba=(0,0,0,0),group=3)
act=add(m,'actuator')
for i in range(2):
    for name,limit in [('insert',40),('lift',40),('flip',6),('twist',2)]:
        add(act,'motor',name=f'core{i}_{name}_motor',joint=f'core{i}_{name}',gear=1,ctrlrange=(-limit,limit))
indent(m,space='  ')
(ROOT/'models/tech_core.xml').write_text('<?xml version="1.0" encoding="utf-8"?>\n'+tostring(m,encoding='unicode')+'\n')
print('Generated original-mesh scene:',len(CORE['meshes']),'core parts per station')
