#!/usr/bin/env python3
"""Regenerate the checked-in MJCF. Runtime simulation is entirely C++/MuJoCo.

Official dimensions: rulebook V2.2.0 pp.64,81–82. Decorative shell thickness,
material properties, hidden mechanisms and inertias are engineering assumptions.
The constrained assembly is a manipulation fixture, not an unconstrained robot.
"""
from math import cos, sin, tan, pi, sqrt
from pathlib import Path
from xml.etree.ElementTree import Element, SubElement, indent, tostring

ROOT = Path(__file__).resolve().parents[1]
N = 24
PIVOT_X = -.169
PIVOT_Z = .108  # Active P height .208m after .100m lift; hidden linkage is approximate.


def fmt(seq):
    return ' '.join(f'{x:.9g}' for x in seq)


def add(parent, tag, **kwargs):
    return SubElement(parent, tag, {k: fmt(v) if isinstance(v, (tuple,list)) else str(v) for k,v in kwargs.items()})


def geom(parent, name, kind, **kw):
    return add(parent, 'geom', name=name, type=kind, **kw)


def wedge_mesh(asset, name, inner, outer, length):
    """A convex annular sector; 24 sectors preserve an inscribed 40mm opening."""
    a = pi/N
    rin = inner/cos(a)
    vertices=[]
    for x in (0, length):
        for r,theta in ((rin,-a),(outer,-a),(outer,a),(rin,a)):
            vertices += [x,r*cos(theta),r*sin(theta)]
    # Explicit triangulation also makes this a closed visual mesh.
    faces=(0,2,1,0,3,2,4,5,6,4,6,7,0,1,5,0,5,4,1,2,6,1,6,5,
           2,3,7,2,7,6,3,0,4,3,4,7)
    add(asset,'mesh',name=name,vertex=vertices,face=faces)


def prism_mesh(asset, name, yz, xlo, xhi):
    vs=[]
    for x in (xlo,xhi):
        for y,z in yz: vs += [x,y,z]
    # MuJoCo computes a convex hull, sufficient for the approximate shell.
    add(asset,'mesh',name=name,vertex=vs)


m=Element('mujoco',model='RoboMaster 2026 technology core / constrained fixture')
m.append(__import__('xml.etree.ElementTree',fromlist=['Comment']).Comment(
    ' GENERATED by scripts/generate_model.py; SI units; +X out from panel, +Z up. '
    'Opening starts at E and insertion travels -X. Q turns the panel-normal bearing; '
    'P flips the pillar, so Q is NOT rotation about the flipped pillar. '))
add(m,'compiler',angle='radian',autolimits='true',inertiafromgeom='auto')
opt=add(m,'option',timestep=.001,integrator='implicitfast',gravity=(0,0,-9.81),
        iterations=80,tolerance='1e-9',cone='elliptic')
# Explicit masks keep intentional peg/unit contacts even for directly nested bodies.
add(opt,'flag',filterparent='disable')
add(m,'size',njmax=2000,nconmax=1000)
stat=add(m,'statistic',center=(0,0,.65),extent=1.9)
visual=add(m,'visual')
add(visual,'global',offwidth=1440,offheight=1000,azimuth=135,elevation=-16)
add(visual,'quality',shadowsize=4096,offsamples=4)
add(visual,'headlight',ambient=(.25,.25,.27),diffuse=(.75,.75,.75),specular=(.35,.35,.35))
add(visual,'rgba',haze=(.08,.11,.16,1))
default=add(m,'default')
add(default,'geom',contype=0,conaffinity=0,condim=4,friction=(.35,.005,.0001),
    solref=(.004,1),solimp=(.95,.99,.001),margin=0)
add(default,'joint',limited='true',armature=.0001)
add(default,'site',size=.004,rgba=(.2,.9,.9,.0))
asset=add(m,'asset')
add(asset,'texture',name='floor_texture',type='2d',builtin='checker',width=512,height=512,
    rgb1=(.15,.185,.23),rgb2=(.18,.215,.26))
add(asset,'texture',name='sky',type='skybox',builtin='gradient',rgb1=(.06,.09,.14),
    rgb2=(.25,.31,.4),width=512,height=3072)
for name,rgba,metal in [
    ('shell',(.07,.085,.10,1),.25),('shell_edge',(.19,.22,.25,1),.6),
    ('carbon',(.025,.032,.038,1),.15),('steel',(.45,.52,.57,1),.8),
    ('unit_shell',(.36,.4,.44,1),.65),('energy',(.88,.8,.52,1),.35),
    ('white',(.9,.92,.91,1),.25),('red',(.9,.035,.06,1),.3),
    ('blue',(.035,.27,.95,1),.3)]:
    add(asset,'material',name=name,rgba=rgba,specular=metal,shininess=.6)
add(asset,'material',name='floor',texture='floor_texture',texrepeat=(8,8),reflectance=.12)
# Figure 5-9: slanted edges259mm and vertical edges307mm.
half_width=.259*cos(pi/6)
profile=[(0,-.07),(half_width,.0595),(half_width,.3665),(0,.496),
         (-half_width,.3665),(-half_width,.0595)]
prism_mesh(asset,'shell_mesh',profile,-.225,-.176)
prism_mesh(asset,'face_mesh',[(y*.976,.21+(z-.21)*.976) for y,z in profile],-.176,-.17)
wedge_mesh(asset,'unit_open_flange',.020,.040,.025)
wedge_mesh(asset,'unit_tube',.020,.030,.075)
world=add(m,'worldbody')
geom(world,'ground','plane',size=(3,3,.1),material='floor',contype=16,conaffinity=15)
add(world,'light',name='key',pos=(1.2,-2.3,3.6),dir=(-.4,.5,-1),diffuse=(.8,.82,.85))
add(world,'light',name='rim',pos=(-2,1.5,2.2),dir=(.5,-.4,-.6),diffuse=(.4,.5,.7),castshadow='false')
# Track-camera fallback is supplemented by the C++ viewer's interactive camera.
add(world,'camera',name='overview',pos=(1.9,-2.6,1.75),xyaxes=(.807,.590,0,-.201,.275,.940),fovy=39)
geom(world,'platform','box',pos=(-.14,0,.055),size=(.40,.75,.055),material='carbon')
geom(world,'platform_top','box',pos=(-.14,0,.112),size=(.38,.73,.007),material='steel')
for i in range(2):
    pref=f'core{i}'
    pole_bit,unit_bit=(1,2) if i==0 else (4,8)
    team='red' if i==0 else 'blue'
    y=-.30 if i==0 else .30
    base=add(world,'body',name=f'{pref}_base',mocap='true',pos=(0,y,.51))
    add(base,'site',name=f'{pref}_origin',pos=(0,0,0))
    geom(base,f'{pref}_support','box',pos=(-.225,0,-.2),size=(.035,.06,.19),material='steel')
    geom(base,f'{pref}_shell','mesh',mesh='shell_mesh',material='shell_edge')
    geom(base,f'{pref}_face','mesh',mesh='face_mesh',material='shell')
    # Raised central channel and a visible carriage track.
    geom(base,f'{pref}_channel','box',pos=(-.159,0,.105),size=(.013,.056,.19),material='carbon')
    for side in (-1,1):
        geom(base,f'{pref}_rail_{side}','box',pos=(-.142,.049*side,.092),
             size=(.009,.005,.146),material='steel')
        geom(base,f'{pref}_side_frame_{side}','box',pos=(-.163,.119*side,.103),
             size=(.012,.033,.084),material='carbon')
    geom(base,f'{pref}_side_left','box',pos=(-.15,-.119,.103),size=(.0015,.0275,.0775),material=team)
    geom(base,f'{pref}_side_right','box',pos=(-.15,.119,.103),size=(.0015,.0275,.0775),material=team)
    #37 explicit fan lamps: +/-90deg, inclusive, in5deg increments.
    for j in range(37):
        ang=(-90+5*j)*pi/180
        outline_r=min(.285/(cos(ang)+tan(pi/6)*abs(sin(ang))),
                      half_width/max(abs(sin(ang)),1e-9))
        radius=outline_r-.032
        geom(base,f'{pref}_led_{j}','box',pos=(-.168,-radius*sin(ang),.211+radius*cos(ang)),
             size=(.0018,.0027,.023),euler=(ang,0,0),material='white')
    # Decorative fasteners and outlines make the unknown shell construction visible.
    for side in (-1,1):
        for z in (-.027,.042,.112,.182,.252):
            geom(base,f'{pref}_bolt_{side}_{str(z).replace(".","_")}',
                 'cylinder',pos=(-.140,.037*side,z),size=(.0032,.0016),
                 quat=(sqrt(.5),0,sqrt(.5),0),material='steel')
    lift=add(base,'body',name=f'{pref}_carriage')
    add(lift,'inertial',pos=(-.15,0,.025),mass=.6,diaginertia=(.002,.002,.001))
    add(lift,'joint',name=f'{pref}_lift',type='slide',axis=(0,0,1),range=(0,.1),
        damping=0,frictionloss=10)
    geom(lift,f'{pref}_carriage_plate','box',pos=(-.125,0,.065),size=(.01,.048,.088),material='shell_edge')
    twist=add(lift,'body',name=f'{pref}_q_bearing',pos=(PIVOT_X,0,PIVOT_Z))
    add(twist,'inertial',pos=(0,0,0),mass=.3,diaginertia=(.001,.001,.001))
    add(twist,'joint',name=f'{pref}_twist',type='hinge',axis=(1,0,0),range=(-pi/2,pi/2),damping=0,frictionloss=0)
    geom(twist,f'{pref}_q_housing','cylinder',pos=(.018,0,0),size=(.038,.02),
         quat=(sqrt(.5),0,sqrt(.5),0),material='steel')
    flip=add(twist,'body',name=f'{pref}_p_bearing')
    add(flip,'inertial',pos=(.09,0,0),mass=.45,diaginertia=(.0006,.0025,.0025))
    add(flip,'joint',name=f'{pref}_flip',type='hinge',axis=(0,-1,0),range=(0,pi/2),damping=.15,frictionloss=.02)
    geom(flip,f'{pref}_bracket','capsule',fromto=(.015,0,0,.060,0,-PIVOT_Z),size=(.017,),material='shell_edge')
    geom(flip,f'{pref}_mark_frame','box',pos=(.065,0,-PIVOT_Z),size=(.005,.049,.049),material='carbon')
    geom(flip,f'{pref}_mark','box',pos=(.0702,0,-PIVOT_Z),size=(.0003,.04,.04),material=team)
    # Black mask with bright 8mm strokes around the aperture resembles Fig5-8.
    geom(flip,f'{pref}_mark_mask','box',pos=(.071,0,-PIVOT_Z),size=(.0003,.036,.036),material='carbon')
    for side in (-1,1):
        geom(flip,f'{pref}_mark_h_{side}','box',pos=(.0715,.019*side,-PIVOT_Z+.029*side),size=(.0003,.014,.004),material='white')
        geom(flip,f'{pref}_mark_v_{side}','box',pos=(.0715,.029*side,-PIVOT_Z+.019*side),size=(.0003,.004,.014),material='white')
    for j,(yy,zz) in enumerate(((.028,-.028),(.028,-.012),(.012,-.028))):
        geom(flip,f'{pref}_mark_dot_{j}','box',pos=(.0715,yy,-PIVOT_Z+zz),size=(.0004,.004,.004),material='white')
    # Cylinder .036m diameter, exactly .100m exposed in front of stop/mark.
    geom(flip,f'{pref}_peg','cylinder',pos=(.119,0,-PIVOT_Z),size=(.018,.05),
         quat=(sqrt(.5),0,sqrt(.5),0),material='carbon',contype=pole_bit,conaffinity=unit_bit)
    for j in range(4):
        ang=j*pi/2
        geom(flip,f'{pref}_peg_stripe_{j}','box',pos=(.121,.0181*cos(ang),-PIVOT_Z+.0181*sin(ang)),
             size=(.032,.00025,.0023),euler=(ang,0,0),material='white')
    geom(flip,f'{pref}_peg_tip','cylinder',pos=(.169,0,-PIVOT_Z),size=(.009,.0002),
         quat=(sqrt(.5),0,sqrt(.5),0),material='steel')
    add(flip,'site',name=f'{pref}_tip',pos=(.169,0,-PIVOT_Z),rgba=(.2,.8,.2,0))
    unit=add(flip,'body',name=f'{pref}_energy_unit',pos=(.169,0,-PIVOT_Z))
    add(unit,'inertial',pos=(.075,0,0),mass=.4,diaginertia=(.00026,.00085,.00085))
    add(unit,'joint',name=f'{pref}_insert',type='slide',axis=(-1,0,0),range=(0,.1),damping=0,frictionloss=10)
    add(unit,'site',name=f'{pref}_grip',pos=(.09,0,0),size=.006)
    add(unit,'site',name=f'{pref}_opening',pos=(0,0,0))
    for j in range(N):
        for part,x,mesh,mat in [('flange',0,'unit_open_flange','unit_shell'),
                              ('tube',.025,'unit_tube','energy')]:
            geom(unit,f'{pref}_unit_{part}_{j}','mesh',mesh=mesh,pos=(x,0,0),
                 euler=(2*pi*j/N,0,0),material=mat,contype=unit_bit,conaffinity=pole_bit)
    geom(unit,f'{pref}_unit_iron','cylinder',pos=(.105,0,0),size=(.030,.005),
         quat=(sqrt(.5),0,sqrt(.5),0),material='steel',contype=unit_bit,conaffinity=pole_bit)
    geom(unit,f'{pref}_unit_cap','cylinder',pos=(.13,0,0),size=(.0475,.02),
         quat=(sqrt(.5),0,sqrt(.5),0),material='unit_shell',contype=unit_bit,conaffinity=pole_bit)
    geom(unit,f'{pref}_unit_cap_inlay','cylinder',pos=(.1503,0,0),size=(.0425,.0003),
         quat=(sqrt(.5),0,sqrt(.5),0),material='steel')
    for j in range(6):
        ang=j*pi/3
        geom(unit,f'{pref}_unit_strut_{j}','capsule',fromto=(.024,.031*cos(ang),.031*sin(ang),.114,.031*cos(ang),.031*sin(ang)),
             size=(.003,),material='carbon')
actuator=add(m,'actuator')
for i in range(2):
    for j,limit in [('insert',40),('lift',40),('flip',6),('twist',2)]:
        add(actuator,'motor',name=f'core{i}_{j}_motor',joint=f'core{i}_{j}',gear=1,ctrlrange=(-limit,limit))
indent(m,space='  ')
path=ROOT/'models'/'tech_core.xml'
path.write_text('<?xml version="1.0" encoding="utf-8"?>\n'+tostring(m,encoding='unicode')+'\n',encoding='utf8')
print(path)
